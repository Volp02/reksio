/** Ablauf, keine Störung: nicht als Problem anzeigen und nicht melden */
export const GEN4_QUIET = /^(return_to_|busy_charging|recovering_location|charging_|acquiring_persistent_map_ids|creating_and_uploading_map|routine_cleaning_start$|confirm_start_after_charge|needs_to_recharge|dustbin_emptied)/

export function gen4CodeText(lang: 'de' | 'en', code: string): string | undefined {
    if (/^(swu_|tron_)/.test(code)) return lang === 'de' ? 'Update fehlgeschlagen' : 'Update failed'
    return (lang === 'de' ? GEN4_CODES_DE : GEN4_CODES_EN)[code]
}
